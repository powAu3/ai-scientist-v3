#!/usr/bin/env python3
"""Generate review-backed manuscript figures from workflow artifacts.

This script keeps figure generation inside the repository workflow instead of
relying on one-off notebook or shell snippets. It does not run experiments; it
visualizes the current protocol-estimated CSV values and deterministic protocol
diagrams.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Optional


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def uncertainty(value: str) -> float:
    cleaned = value.replace("+-", "").replace("±", "").strip()
    try:
        return float(cleaned)
    except ValueError:
        return 0.0


def pick(
    rows: list[dict[str, str]],
    metric: str,
    methods: list[str],
    dataset_contains: Optional[str] = None,
) -> list[tuple[str, float, float]]:
    selected: list[tuple[str, float, float]] = []
    for method in methods:
        matches = [
            row
            for row in rows
            if row.get("metric") == metric and row.get("method") == method
        ]
        if dataset_contains:
            matches = [
                row
                for row in matches
                if dataset_contains in row.get("dataset_bucket", "")
            ]
        if not matches:
            continue
        row = matches[0]
        selected.append(
            (
                method,
                float(row.get("predicted_value", "0")),
                uncertainty(row.get("uncertainty", "0")),
            )
        )
    return selected


def draw_architecture_figure(plt, output: Path) -> None:
    """Draw the deterministic candidate-instantiation architecture diagram."""
    import matplotlib.patches as patches

    fig, ax = plt.subplots(figsize=(9.4, 4.8), constrained_layout=True)
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 6)
    ax.axis("off")

    def box(x: float, y: float, w: float, h: float, label: str, color: str) -> None:
        rect = patches.FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0.04,rounding_size=0.07",
            facecolor=color,
            edgecolor="#242424",
            linewidth=1.0,
        )
        ax.add_patch(rect)
        ax.text(x + w / 2, y + h / 2, label, ha="center", va="center", fontsize=9)

    def arrow(x1: float, y1: float, x2: float, y2: float) -> None:
        ax.annotate(
            "",
            xy=(x2, y2),
            xytext=(x1, y1),
            arrowprops={"arrowstyle": "->", "lw": 1.2, "color": "#242424"},
        )

    box(0.3, 3.0, 1.45, 0.8, "Road-crack\nimages", "#d9e8ff")
    box(2.15, 3.0, 1.55, 0.8, "YOLO\nbackbone", "#dff2e2")
    box(4.05, 3.0, 1.75, 0.8, "Shape-aware\nneck", "#f5ead0")
    box(6.2, 3.0, 1.65, 0.8, "Thin-crack\nheads", "#f5dede")
    box(8.25, 3.0, 1.45, 0.8, "Boxes,\nmasks,\nscores", "#e4dff4")

    for x1, x2 in [(1.75, 2.15), (3.7, 4.05), (5.8, 6.2), (7.85, 8.25)]:
        arrow(x1, 3.4, x2, 3.4)

    box(2.0, 1.25, 2.1, 0.85, "Hard-negative\nsampling queue", "#f0f0f0")
    box(4.55, 1.25, 2.1, 0.85, "Boundary +\nelongation losses", "#f0f0f0")
    box(7.1, 1.25, 2.1, 0.85, "Matched-budget\nprotocol hooks", "#f0f0f0")
    arrow(3.05, 2.1, 4.85, 3.0)
    arrow(5.6, 2.1, 5.15, 3.0)
    arrow(8.15, 2.1, 7.1, 3.0)

    ax.text(
        0.35,
        5.35,
        "Candidate detector instantiation inside a protocol-first evaluation contract",
        fontsize=12,
        weight="bold",
    )
    ax.text(
        0.35,
        0.35,
        "Diagram is generated by scripts/generate_predicted_figures.py from the fixed workflow spec; it is not measured model evidence.",
        fontsize=8,
        color="#555555",
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=220, bbox_inches="tight")
    plt.close(fig)


