def draw_benchmark_matrix_figure(plt, output: Path) -> None:
    """Draw the deterministic benchmark coverage matrix."""
    methods = [
        "YOLOv8s",
        "YOLOv8-PD",
        "BL-YOLOv8",
        "RT-DETR",
        "DeepCrack",
        "CrackFormer",
        "CrackYOLO-R",
    ]
    columns = [
        "Same\nbudget",
        "Crack\nspecific",
        "Hard\nnegatives",
        "Speed\ncheck",
        "Stats\nplan",
    ]
    values = [
        [3, 1, 2, 3, 2],
        [3, 3, 2, 2, 2],
        [3, 3, 2, 2, 2],
        [2, 1, 2, 1, 2],
        [1, 3, 2, 1, 2],
        [1, 3, 2, 1, 2],
        [3, 3, 3, 3, 3],
    ]

    fig, ax = plt.subplots(figsize=(8.8, 5.8), constrained_layout=True)
    image = ax.imshow(values, cmap="YlGnBu", vmin=0, vmax=3)
    ax.set_xticks(range(len(columns)), labels=columns)
    ax.set_yticks(range(len(methods)), labels=methods)
    ax.tick_params(axis="both", labelsize=9)
    ax.set_title("Planned Benchmark Coverage Matrix", fontsize=13, weight="bold")

    for row_idx, row in enumerate(values):
        for col_idx, value in enumerate(row):
            ax.text(
                col_idx,
                row_idx,
                str(value),
                ha="center",
                va="center",
                color="#111111" if value < 2 else "white",
                fontsize=8,
                weight="bold",
            )

    cbar = fig.colorbar(image, ax=ax, shrink=0.86)
    cbar.set_label("0-3 protocol coverage priority, not performance", fontsize=9)
    fig.text(
        0.5,
        0.02,
        "Cells encode planned coverage pressure for the evaluation contract; they are not measured or forecast scores.",
        ha="center",
        fontsize=8.5,
        color="#555555",
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=220, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--app-dir", default=".", help="Application root directory")
    parser.add_argument(
        "--output",
        default=None,
        help="Output PNG path; default: <app-dir>/figures/predicted_yolo_crack_results.png",
    )
    args = parser.parse_args()

    root = Path(args.app_dir)
    csv_path = root / "predicted_results" / "predicted_results.csv"
    output = (
        Path(args.output)
        if args.output
        else root / "figures" / "predicted_yolo_crack_results.png"
    )

    rows = read_rows(csv_path)
    if not rows:
        raise SystemExit(f"No predicted rows found: {csv_path}")

    try:
        import matplotlib.pyplot as plt
    except Exception as exc:  # pragma: no cover - environment failure path
        raise SystemExit(f"matplotlib is required to generate figures: {exc}")

    panels = [
        (
            "Crack500 boxes",
            "mAP50-95",
            pick(
                rows,
                "mAP50-95",
                ["YOLOv8s baseline", "Faster R-CNN baseline", "CrackYOLO-R full"],
                "Crack500",
            ),
            "higher",
        ),
        (
            "RDD2022 crack subset",
            "mAP50-95",
            pick(
                rows,
                "mAP50-95",
                [
                    "YOLOv8s baseline",
                    "YOLOv8-PD baseline",
                    "Improved YOLOv8s road-defect baseline",
                    "BL-YOLOv8 baseline",
                    "Damage Shape Adaptation detector",
                    "RT-DETR-R18/R50 family",
                    "CrackYOLO-R full",
                ],
                "RDD2022",
            ),
            "higher",
        ),
        (
            "Thin-structure masks",
            "F1@thin-crack",
            pick(
                rows,
                "F1@thin-crack",
                [
                    "YOLOv8s-seg baseline",
                    "DeepCrack segmentation baseline",
                    "CrackFormer baseline",
                    "Crack Transformer baseline",
                    "ViT crack detector baseline",
                    "CrackYOLO-R-seg full",
                ],
                "DeepCrack",
            ),
            "higher",
        ),
        (
            "Hard-negative audit",
            "FP/image",
            pick(
                rows,
                "false_positive_per_image",
                [
                    "YOLOv8s baseline",
                    "Damage Shape Adaptation detector",
                    "CrackYOLO-R full",
                ],
                "Shadow",
            ),
            "lower",
        ),
        (
            "Edge imagery",
            "FPS@640",
            pick(rows, "FPS@640", ["YOLOv8n baseline", "CrackYOLO-R-nano"], "Inspection"),
            "higher",
        ),
    ]

    if not any(panel[2] for panel in panels):
        raise SystemExit("No known method/metric rows found for predicted figure panels")

    plt.rcParams.update(
        {
            "font.size": 8,
            "font.family": "DejaVu Sans",
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )
    fig, axes = plt.subplots(2, 3, figsize=(10.2, 5.8), constrained_layout=True)
    flat_axes = axes.ravel()

    colors = {
        "CrackYOLO-R full": "#2a7f62",
        "CrackYOLO-R-seg full": "#2a7f62",
        "CrackYOLO-R-nano": "#2a7f62",
        "YOLOv8s baseline": "#4a6fa5",
        "YOLOv8n baseline": "#4a6fa5",
        "YOLOv8s-seg baseline": "#4a6fa5",
        "Improved YOLOv8s road-defect baseline": "#5c5c5c",
        "YOLOv8-PD baseline": "#5c5c5c",
        "BL-YOLOv8 baseline": "#5c5c5c",
        "Damage Shape Adaptation detector": "#8a6d3b",
        "CrackFormer baseline": "#7b4fa3",
        "Crack Transformer baseline": "#7b4fa3",
        "ViT crack detector baseline": "#7b4fa3",
        "DeepCrack segmentation baseline": "#7b4fa3",
        "Faster R-CNN baseline": "#9a4f4f",
        "RT-DETR-R18/R50 family": "#9a4f4f",
    }
    label_map = {
        "YOLOv8s baseline": "YOLOv8s",
        "YOLOv8n baseline": "YOLOv8n",
        "Faster R-CNN baseline": "Faster R-CNN",
        "YOLOv8-PD baseline": "YOLOv8-PD",
        "Improved YOLOv8s road-defect baseline": "Imp. YOLOv8s",
        "BL-YOLOv8 baseline": "BL-YOLOv8",
        "Damage Shape Adaptation detector": "DSA detector",
        "RT-DETR-R18/R50 family": "RT-DETR",
        "YOLOv8s-seg baseline": "YOLOv8s-seg",
        "DeepCrack segmentation baseline": "DeepCrack",
        "CrackFormer baseline": "CrackFormer",
        "Crack Transformer baseline": "Crack Trans.",
        "ViT crack detector baseline": "ViT crack",
        "CrackYOLO-R full": "CrackYOLO-R",
        "CrackYOLO-R-seg full": "CrackYOLO-R-seg",
        "CrackYOLO-R-nano": "CrackYOLO-R-nano",
    }

    for ax, (title, ylabel, data, direction) in zip(flat_axes, panels):
        if not data:
            ax.axis("off")
            continue
        labels = [label_map.get(method, method) for method, _, _ in data]
        vals = [value for _, value, _ in data]
        xs = list(range(len(data)))
        ax.bar(
            xs,
            vals,
            color=[colors.get(method, "#666666") for method, _, _ in data],
            alpha=0.92,
            edgecolor="black",
            linewidth=0.4,
        )
        ax.set_title(title, fontsize=9, fontweight="bold")
        ax.set_ylabel(ylabel)
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, rotation=35, ha="right")
        ax.grid(axis="y", alpha=0.2, linewidth=0.6)
        spread = max(vals) - min(vals)
        pad = max(0.04, spread * 0.18)
        lo = min(vals) - pad
        hi = max(vals) + pad
        if ylabel == "FP/image":
            lo = max(0.0, lo)
        elif "FPS" not in ylabel:
            lo = max(0.0, lo)
            hi = min(1.0, hi)
        ax.set_ylim(lo, hi)
        ax.text(
            0.98,
            0.92,
            "lower is better" if direction == "lower" else "higher is better",
            transform=ax.transAxes,
            ha="right",
            va="top",
            fontsize=7,
            color="#555555",
        )

    flat_axes[-1].axis("off")
    flat_axes[-1].text(
        0.02,
        0.8,
        "Panels use metric-specific axes.\n"
        "Bars are planning centers only;\n"
        "planning ranges remain in CSV.",
        fontsize=9,
        va="top",
    )
    fig.suptitle("CrackYOLO-R Planning Forecast Centers by Metric Family", fontsize=12, fontweight="bold")
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=220, bbox_inches="tight")
    plt.close(fig)
    draw_module_detail_figure(plt, root / "figures" / "crackyolo_module_detail.png")
    draw_mechanism_equation_figure(plt, root / "figures" / "crackyolo_mechanism_equations.png")
    draw_architecture_figure(plt, root / "figures" / "crackyolo_architecture.png")
    draw_benchmark_matrix_figure(plt, root / "figures" / "planned_benchmark_matrix.png")
    print(f"Wrote {output} ({output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
